"""Daily trivia challenge: the same 5 questions for everyone each UTC day.

The set is generated by the existing TriviaGenerator with `random` seeded from the date (two
easy, two medium, one hard), kept in memory for the day and never sent with its answers.
`GET /api/trivia/daily` returns the date and the questions; `POST /api/trivia/daily/check`
takes the answers and returns correctness and the right answers. The answers only come back
from the check, and the client keeps one attempt per day.
"""
import hashlib
import random
import threading
from datetime import datetime, timezone
from typing import Callable, Dict, List, Optional

from fastapi import Depends, FastAPI, HTTPException
from pydantic import BaseModel, Field

from trivia.trivia_generator import Difficulty, TriviaGenerator, TriviaQuestion

# Difficulty of each of the day's questions, in order
PLAN = [Difficulty.EASY, Difficulty.EASY, Difficulty.MEDIUM, Difficulty.MEDIUM, Difficulty.HARD]
MAX_ATTEMPTS_PER_QUESTION = 25

_lock = threading.Lock()
_cache: Dict[str, List[TriviaQuestion]] = {}


def today_utc() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d")


def seed_for(date: str) -> int:
    return int(hashlib.sha256(f"pitch-me-daily-trivia:{date}".encode()).hexdigest()[:12], 16)


def build_daily(conn, date: str, generator_cls=TriviaGenerator) -> List[TriviaQuestion]:
    """Generate the day's questions with `random` seeded from the date (state restored after)."""
    gen = generator_cls(conn)
    state = random.getstate()
    random.seed(seed_for(date))
    try:
        questions: List[TriviaQuestion] = []
        for i, level in enumerate(PLAN):
            for _ in range(MAX_ATTEMPTS_PER_QUESTION):
                q = gen.generate_question(difficulty=level)
                if q and q.question not in {x.question for x in questions} and len(q.options) >= 2:
                    q.question_id = f"daily-{date}-{i + 1}"  # stable ids, not a random uuid
                    questions.append(q)
                    break
        return questions
    finally:
        random.setstate(state)


def get_daily(conn, date: Optional[str] = None, generator_cls=TriviaGenerator) -> List[TriviaQuestion]:
    date = date or today_utc()
    with _lock:
        if date in _cache:
            return _cache[date]
        questions = build_daily(conn, date, generator_cls)
        if len(questions) < len(PLAN):
            raise HTTPException(status_code=503, detail="Today's questions could not be built yet")
        _cache.clear()  # only the current day is kept
        _cache[date] = questions
        return questions


def public_question(q: TriviaQuestion) -> dict:
    """The question as the player sees it: no answer, explanation or source."""
    return {
        "question_id": q.question_id,
        "question": q.question,
        "options": list(q.options),
        "category": q.category.value,
        "difficulty": q.difficulty.value,
    }


class DailyAnswer(BaseModel):
    question_id: str = Field(max_length=64)
    answer: str = Field(max_length=300)


class DailyCheckRequest(BaseModel):
    date: str = Field(max_length=10)
    answers: List[DailyAnswer] = Field(max_length=10)


def check_daily(questions: List[TriviaQuestion], answers: List[DailyAnswer], generator_cls=TriviaGenerator) -> dict:
    gen = generator_cls(None)
    given = {a.question_id: a.answer for a in answers}
    results = []
    for q in questions:
        answer = given.get(q.question_id)
        correct = False
        if answer is not None:
            correct, _ = gen.check_answer(q, answer)
        results.append({
            "question_id": q.question_id,
            "correct": correct,
            "correct_answer": q.correct_answer,
            "explanation": q.explanation,
        })
    return {"score": sum(1 for r in results if r["correct"]), "total": len(results), "results": results}


def register(app: FastAPI, get_conn: Callable) -> None:
    @app.get("/api/trivia/daily")
    def daily(conn=Depends(get_conn)):
        questions = get_daily(conn)
        return {"date": today_utc(), "questions": [public_question(q) for q in questions]}

    @app.post("/api/trivia/daily/check")
    def daily_check(request: DailyCheckRequest, conn=Depends(get_conn)):
        if request.date != today_utc():
            raise HTTPException(status_code=409, detail="That challenge is over; reload for today's questions")
        questions = get_daily(conn, request.date)
        return {"date": request.date, **check_daily(questions, request.answers)}
